package com.example.rootpanel;
public class Entity {
    public float x, y, w, h; public int color; public float[] lines; public int lineColor;
    public Entity(float x, float y, float w, float h, int color, float[] lines, int lineColor) {
        this.x = x; this.y = y; this.w = w; this.h = h; this.color = color; this.lines = lines; this.lineColor = lineColor;
    }
}
